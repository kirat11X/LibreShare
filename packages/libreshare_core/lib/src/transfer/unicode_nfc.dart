/// Unicode NFC normalization for file names (no unicode package is available).
///
/// Implements the canonical decomposition, canonical ordering and canonical
/// composition algorithms (UAX #15) for the Basic Multilingual Plane, using
/// tables generated from Unicode data: Latin (incl. Vietnamese), Greek,
/// Cyrillic, Hebrew/Arabic/Indic compositions, Japanese kana voicing marks,
/// plus algorithmic Hangul. Known limitation: code points outside the BMP
/// (e.g. musical symbols, CJK compatibility supplement U+2F800..) and the CJK
/// compatibility ideographs U+F900..U+FAFF are passed through unchanged.
library;

/// Returns [input] in Unicode Normalization Form C.
String nfcNormalize(String input) {
  // Every string made only of code units below U+0300 is already NFC: no
  // combining marks exist there and no code point decomposes into a pair that
  // would recompose differently.
  var needsWork = false;
  for (final u in input.codeUnits) {
    if (u >= 0x300) {
      needsWork = true;
      break;
    }
  }
  if (!needsWork) return input;

  final decomposed = <int>[];
  for (final r in input.runes) {
    _decompose(r, decomposed);
  }
  _reorder(decomposed);
  return String.fromCharCodes(_compose(decomposed));
}

// Hangul constants (Unicode 3.12).
const int _sBase = 0xAC00;
const int _lBase = 0x1100;
const int _vBase = 0x1161;
const int _tBase = 0x11A7;
const int _lCount = 19;
const int _vCount = 21;
const int _tCount = 28;
const int _nCount = _vCount * _tCount;
const int _sCount = _lCount * _nCount;

void _decompose(int r, List<int> out) {
  if (r < 0xC0) {
    out.add(r);
    return;
  }
  final sIndex = r - _sBase;
  if (sIndex >= 0 && sIndex < _sCount) {
    out.add(_lBase + sIndex ~/ _nCount);
    out.add(_vBase + (sIndex % _nCount) ~/ _tCount);
    final t = sIndex % _tCount;
    if (t != 0) out.add(_tBase + t);
    return;
  }
  final m = _decompositions[r];
  if (m == null) {
    out.add(r);
    return;
  }
  for (final part in m) {
    _decompose(part, out);
  }
}

void _reorder(List<int> cps) {
  // Stable insertion sort of each run of non-starters by combining class.
  for (var i = 1; i < cps.length; i++) {
    final c = _ccc(cps[i]);
    if (c == 0) continue;
    var j = i;
    while (j > 0) {
      final prev = _ccc(cps[j - 1]);
      if (prev <= c) break;
      final tmp = cps[j];
      cps[j] = cps[j - 1];
      cps[j - 1] = tmp;
      j--;
    }
  }
}

List<int> _compose(List<int> cps) {
  if (cps.isEmpty) return cps;
  final result = <int>[cps[0]];
  var starterPos = 0;
  var starter = cps[0];
  var lastClass = _ccc(starter);
  if (lastClass != 0) {
    lastClass = 256; // irregular sequence starting with a mark
  }
  for (var i = 1; i < cps.length; i++) {
    final ch = cps[i];
    final chClass = _ccc(ch);
    final composite = _composePair(starter, ch);
    if (composite != null && (lastClass < chClass || lastClass == 0)) {
      result[starterPos] = composite;
      starter = composite;
    } else {
      if (chClass == 0) {
        starterPos = result.length;
        starter = ch;
      }
      lastClass = chClass;
      result.add(ch);
    }
  }
  return result;
}

int? _composePair(int a, int b) {
  // Hangul L + V, LV + T.
  final lIndex = a - _lBase;
  if (lIndex >= 0 && lIndex < _lCount) {
    final vIndex = b - _vBase;
    if (vIndex >= 0 && vIndex < _vCount) {
      return _sBase + (lIndex * _vCount + vIndex) * _tCount;
    }
  }
  final sIndex = a - _sBase;
  if (sIndex >= 0 && sIndex < _sCount && sIndex % _tCount == 0) {
    final tIndex = b - _tBase;
    if (tIndex > 0 && tIndex < _tCount) return a + tIndex;
  }
  return _compositions[(a << 21) | b];
}

int _ccc(int cp) {
  if (cp < 0x300) return 0;
  // Binary search in the sorted run table.
  var lo = 0;
  var hi = _cccRuns.length ~/ 3 - 1;
  while (lo <= hi) {
    final mid = (lo + hi) >> 1;
    final start = _cccRuns[mid * 3];
    final end = _cccRuns[mid * 3 + 1];
    if (cp < start) {
      hi = mid - 1;
    } else if (cp > end) {
      lo = mid + 1;
    } else {
      return _cccRuns[mid * 3 + 2];
    }
  }
  return 0;
}

final Map<int, List<int>> _decompositions = () {
  final map = <int, List<int>>{};
  for (final entry in _kDecompositions.split(';')) {
    final eq = entry.indexOf('=');
    final cp = int.parse(entry.substring(0, eq), radix: 16);
    map[cp] = [
      for (final p in entry.substring(eq + 1).split(' '))
        int.parse(p, radix: 16),
    ];
  }
  return map;
}();

final Map<int, int> _compositions = () {
  final excluded = {
    for (final h in _kCompositionExclusions.split(',')) int.parse(h, radix: 16),
  };
  final map = <int, int>{};
  _decompositions.forEach((cp, parts) {
    if (parts.length == 2 && !excluded.contains(cp)) {
      map[(parts[0] << 21) | parts[1]] = cp;
    }
  });
  return map;
}();

/// Flattened (start, end, class) triples, sorted by start.
final List<int> _cccRuns = () {
  final out = <int>[];
  for (final run in _kCombiningClasses.split(';')) {
    final dash = run.indexOf('-');
    final eq = run.indexOf('=');
    out
      ..add(int.parse(run.substring(0, dash), radix: 16))
      ..add(int.parse(run.substring(dash + 1, eq), radix: 16))
      ..add(int.parse(run.substring(eq + 1)));
  }
  return out;
}();

